#!/usr/bin/env node
'use strict';

/**
 * scripts/build.js
 * ─────────────────────────────────────────────────────────────────
 * Production build script.
 *
 * What it does:
 *   1. Runs `npm ci` (or `npm install`) in frontend/ and backend/
 *   2. Runs `vite build` in frontend/            → frontend/dist/
 *   3. Cleans backend/public/
 *   4. Copies frontend/dist/ → backend/public/
 *   5. Prints the startup command
 *
 * Usage:
 *   node scripts/build.js          (from project root)
 *   npm run build                   (same, via root package.json)
 *
 * After this runs, start the system with:
 *   cd backend && npm start
 * ─────────────────────────────────────────────────────────────────
 */

const { execSync }  = require('child_process');
const fs            = require('fs');
const path          = require('path');

const ROOT     = path.resolve(__dirname, '..');
const FRONTEND = path.join(ROOT, 'frontend');
const BACKEND  = path.join(ROOT, 'backend');
const DIST     = path.join(FRONTEND, 'dist');
const PUBLIC   = path.join(BACKEND, 'public');

/* ── Colour helpers ─────────────────────────────────────────── */
const G = '\x1b[32m'; const Y = '\x1b[33m';
const B = '\x1b[36m'; const R = '\x1b[31m'; const X = '\x1b[0m';
const log  = (msg)  => console.log(`${G}[build]${X} ${msg}`);
const warn = (msg)  => console.log(`${Y}[build]${X} ${msg}`);
const info = (msg)  => console.log(`${B}[build]${X} ${msg}`);
const err  = (msg)  => console.error(`${R}[build]${X} ${msg}`);
const run  = (cmd, cwd) => {
  info(`$ ${cmd}  (${path.relative(ROOT, cwd) || '.'})`);
  execSync(cmd, { cwd, stdio: 'inherit' });
};

/* ── Copy helper (recursive) ────────────────────────────────── */
function copyDir(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const srcPath  = path.join(src,  entry.name);
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDir(srcPath, destPath);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

/* ════════════════════════════════════════════════════════════ */
console.log(`\n${B}══════════════════════════════════════════════${X}`);
console.log(`${B}  REMS — Production Build                     ${X}`);
console.log(`${B}══════════════════════════════════════════════${X}\n`);

/* ── Step 1 : Install backend dependencies ──────────────────── */
log('Step 1/4 — Installing backend dependencies…');
run('npm install --production=false', BACKEND);

/* ── Step 2 : Install frontend dependencies ─────────────────── */
log('Step 2/4 — Installing frontend dependencies…');
run('npm install', FRONTEND);

/* ── Step 3 : Build the React app ───────────────────────────── */
log('Step 3/4 — Building React app with Vite…');

// Write a production .env for the frontend build.
// VITE_API_BASE_URL=/api  →  axios calls /api/...
// VITE_UPLOADS_URL=        →  image URLs use same-origin /uploads/...
// Both are relative paths, so they work regardless of the server IP.
const frontendEnvProd = [
  '# Auto-generated by scripts/build.js — do not edit manually',
  'VITE_API_BASE_URL=/api',
  'VITE_UPLOADS_URL=',
  'VITE_DEBUG_API=false',
  // Upload size limits must match backend/.env so the frontend validates
  // files before sending and shows accurate error messages.
  `VITE_MAX_FILE_SIZE_MB=${process.env.MAX_FILE_SIZE_MB || 10}`,
  `VITE_MAX_VIDEO_SIZE_MB=${process.env.MAX_VIDEO_SIZE_MB || 500}`,
].join('\n') + '\n';

const frontendEnvPath = path.join(FRONTEND, '.env.production');
fs.writeFileSync(frontendEnvPath, frontendEnvProd);
log(`  Wrote ${path.relative(ROOT, frontendEnvPath)}`);

run('npm run build', FRONTEND);

if (!fs.existsSync(DIST)) {
  err('Vite build failed — frontend/dist not found');
  process.exit(1);
}

const distFiles = fs.readdirSync(DIST);
log(`  Build output: ${distFiles.join(', ')}`);

/* ── Step 4 : Copy dist → backend/public ────────────────────── */
log('Step 4/4 — Copying dist → backend/public…');

// Clean old public/ so stale files don't persist
if (fs.existsSync(PUBLIC)) {
  fs.rmSync(PUBLIC, { recursive: true, force: true });
  log('  Cleaned backend/public/');
}

copyDir(DIST, PUBLIC);

const copiedCount = fs.readdirSync(PUBLIC).length;
log(`  Copied ${copiedCount} items to backend/public/`);

/* ── Verify ──────────────────────────────────────────────────── */
const indexHtml = path.join(PUBLIC, 'index.html');
if (!fs.existsSync(indexHtml)) {
  err('backend/public/index.html not found after copy!');
  process.exit(1);
}

/* ── Done ────────────────────────────────────────────────────── */
console.log(`\n${G}══════════════════════════════════════════════${X}`);
console.log(`${G}  Build complete!                              ${X}`);
console.log(`${G}══════════════════════════════════════════════${X}`);
console.log(`
${Y}Next steps:${X}

  1. Make sure ${Y}backend/.env${X} has ${Y}NODE_ENV=production${X}
     (copy backend/.env.production → backend/.env and fill in values)

  2. Start the server:
       ${G}cd backend && npm start${X}
     or from the project root:
       ${G}npm start${X}

  3. Access the app:
       ${G}http://localhost:5000${X}          (this machine)
       ${G}http://SERVER_LAN_IP:5000${X}      (other LAN devices - run START_SYSTEM.bat to detect IP)

  4. Health check:
       ${G}http://localhost:5000/health${X}

${Y}To rebuild after code changes:${X}
  ${G}npm run build${X}   (from project root)
`);
